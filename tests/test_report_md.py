"""Markdown renderer tests: escaping, humanize, and a full golden report."""

import random
import unittest
from datetime import datetime, timezone

from agent_standup.gitlog import Commit, GitStats, RepoLog
from agent_standup.merge import build_report
from agent_standup.report_md import escape, humanize, render
from agent_standup.sessions import ProjectSummary, SessionStats

UTC = timezone.utc
START = datetime(2026, 1, 1, tzinfo=UTC)
UNTIL = datetime(2026, 1, 8, tzinfo=UTC)
NOW = datetime(2026, 1, 8, 12, 0, tzinfo=UTC)


def tokens(**over):
    base = dict.fromkeys(("input", "output", "cache_read", "cache_creation"), 0)
    base.update(over)
    return base


def project(cwd, sessions=1, active=60.0, turns=1, tools=0, tok=None):
    return ProjectSummary(cwd=cwd, sessions=sessions, active_seconds=active, turns=turns,
                          tool_calls=tools, tokens=tok or tokens())


def commit(subject, ai=False, ins=1, dels=0, files=1):
    return Commit(commit_hash="a" * 40, authored_at=0, subject=subject,
                 co_authors=(["Claude <noreply@anthropic.com>"] if ai else []),
                 insertions=ins, deletions=dels, files_changed=files, ai_assisted=ai)


class EscapeTestCase(unittest.TestCase):
    def test_link_syntax_is_broken_by_bracket_escaping(self):
        self.assertEqual(escape("[x](http://evil)"), "\\[x\\](http://evil)")

    def test_backtick_and_emphasis_markers_are_escaped(self):
        self.assertEqual(escape("`code` *bold* _em_"), "\\`code\\` \\*bold\\* \\_em\\_")

    def test_angle_brackets_and_pipe_are_escaped(self):
        self.assertEqual(escape("<script>|table"), "\\<script\\>\\|table")

    def test_plain_text_is_unchanged(self):
        self.assertEqual(escape("fix: parser bug, take two"), "fix: parser bug, take two")


class HumanizeTestCase(unittest.TestCase):
    def test_hours_and_minutes(self):
        self.assertEqual(humanize(3 * 3600 + 42 * 60), "3h 42m")

    def test_whole_hours_drop_the_minutes(self):
        self.assertEqual(humanize(2 * 3600), "2h")

    def test_under_an_hour_shows_minutes_only(self):
        self.assertEqual(humanize(45 * 60), "45m")

    def test_zero_is_zero_minutes(self):
        self.assertEqual(humanize(0), "0m")


class GoldenReportTestCase(unittest.TestCase):
    def _build(self, seed=0):
        rng = random.Random(seed)
        projects = {
            "/a/quiet": project("/a/quiet", sessions=1, active=600.0, turns=3,
                                tok=tokens(input=10, output=200)),
            "/a/busy": project("/a/busy", sessions=4, active=13320.0, turns=40, tools=12,
                              tok=tokens(input=500, output=9000)),
        }
        stats = SessionStats(projects=dict(rng.sample(list(projects.items()), len(projects))))
        logs = [
            RepoLog(top="/a/busy", commits=[
                commit("add feature", ai=True, ins=20, dels=3, files=2),
                commit("fix typo", ai=False, ins=1, dels=1)]),
            RepoLog(top="/a/quiet", commits=[commit("bump version", ai=True)]),
        ]
        rng.shuffle(logs)
        repo_map = {"/a/busy": "/a/busy", "/a/quiet": "/a/quiet"}
        report = build_report(stats, logs, repo_map, GitStats(), START, UNTIL)
        return render(report, now=NOW)

    def test_golden_report_matches_exactly(self):
        expected = """# Standup report

- Period: 2026-01-01 00:00 to 2026-01-08 00:00 (UTC)
- Sessions: 5
- Active time: 3h 52m
- Commits: 2 AI-assisted, 1 other
- Files changed: 4

## Projects

### a-busy

- Sessions: 4
- Active time: 3h 42m
- Turns: 40
- Tool calls: 12
- Tokens: in 500 / out 9,000
- Related repos: a-busy

### a-quiet

- Sessions: 1
- Active time: 10m
- Turns: 3
- Tool calls: 0
- Tokens: in 10 / out 200
- Related repos: a-quiet

## Repos

### a-busy

- add feature (+20/-3, 2 files)
- 1 other commit (+1/-1)

### a-quiet

- bump version (+1/-0, 1 file)

---
Generated by agent-standup 0.1.0 -- 2026-01-08 12:00 UTC -- redaction: on
"""
        self.assertEqual(self._build(seed=0), expected)

    def test_input_order_permutation_yields_identical_output(self):
        first = self._build(seed=1)
        second = self._build(seed=2)
        third = self._build(seed=99)
        self.assertEqual(first, second)
        self.assertEqual(first, third)


class RedactionBadgeTestCase(unittest.TestCase):
    def test_no_redact_badge_is_loud(self):
        report = build_report(SessionStats(), [], {}, GitStats(), START, UNTIL, redact=False)
        text = render(report, now=NOW)
        self.assertIn("redaction: OFF", text)

    def test_default_redact_badge_is_on(self):
        report = build_report(SessionStats(), [], {}, GitStats(), START, UNTIL)
        text = render(report, now=NOW)
        self.assertIn("redaction: on", text)


class HostileSubjectTestCase(unittest.TestCase):
    def test_hostile_commit_subject_cannot_become_a_link(self):
        logs = [RepoLog(top="/x", commits=[commit("[x](http://evil) `rm -rf`", ai=True)])]
        report = build_report(SessionStats(), logs, {}, GitStats(), START, UNTIL)
        text = render(report, now=NOW)
        # The link's opening bracket is escaped, so the whole construct can
        # never parse as Markdown link syntax -- the raw, unescaped form
        # (the only thing a renderer would ever turn into a link) is absent.
        self.assertNotIn("[x](http://evil)", text)
        self.assertIn("\\[x\\](http://evil)", text)
        self.assertNotIn("`rm -rf`", text)

    def test_zero_projects_and_repos_still_renders_a_valid_header(self):
        report = build_report(SessionStats(), [], {}, GitStats(), START, UNTIL)
        text = render(report, now=NOW)
        self.assertIn("# Standup report", text)
        self.assertNotIn("## Projects", text)
        self.assertNotIn("## Repos", text)


if __name__ == "__main__":
    unittest.main()
