"""Render a :class:`merge.Report` as a paste-ready Markdown standup report.

Every piece of dynamic text --- a commit subject, a project or repo label ---
is neutralized against Markdown control characters before it goes into the
report, and commit subjects are additionally run through the vendored
redactor (labels are already redacted upstream in ``merge.py``), so a
hostile or secret-bearing subject can never turn into live markup or leak a
credential into a report meant to be pasted straight into a chat or an issue.
No links are ever generated by this renderer.
"""

import re
from datetime import datetime, timezone
from typing import Dict, List, Optional

from . import __version__
from ._vendor.redactor import redact_text
from .gitlog import Commit
from .merge import ProjectEntry, Report, RepoEntry

# Backslash-escaping any ASCII punctuation character is always safe under
# CommonMark; these are the characters that can actually turn attacker text
# into live markup (code spans, emphasis, links, autolinks, raw HTML, tables).
_MD_SPECIAL = re.compile(r"[\\`*_\[\]<>|]")


def escape(text: object) -> str:
    """Backslash-escape Markdown control characters in ``text``."""
    return _MD_SPECIAL.sub(lambda match: "\\" + match.group(0), str(text))


def humanize(seconds: float) -> str:
    """"3h 42m" style duration; drops a unit that is exactly zero."""
    total_minutes = int(round(max(0.0, seconds) / 60.0))
    hours, minutes = divmod(total_minutes, 60)
    if hours and minutes:
        return "%dh %dm" % (hours, minutes)
    if hours:
        return "%dh" % hours
    return "%dm" % minutes


def _tokens(tokens: Dict[str, int]) -> str:
    return "in %s / out %s" % ("{:,}".format(tokens.get("input", 0)),
                               "{:,}".format(tokens.get("output", 0)))


def _period(report: Report) -> str:
    return "%s to %s (UTC)" % (report.start.strftime("%Y-%m-%d %H:%M"),
                               report.until.strftime("%Y-%m-%d %H:%M"))


def _header(report: Report) -> List[str]:
    totals = report.totals
    lines = [
        "# Standup report", "",
        "- Period: %s" % _period(report),
        "- Sessions: %d" % totals.sessions,
        "- Active time: %s" % humanize(totals.active_seconds),
        "- Commits: %d AI-assisted, %d other" % (totals.ai_commits, totals.other_commits),
        "- Files changed: %d" % totals.files_changed,
    ]
    skips = []  # type: List[str]
    if totals.repos_skipped:
        skips.append("%d repos skipped" % totals.repos_skipped)
    if totals.files_skipped:
        skips.append("%d files skipped" % totals.files_skipped)
    if skips:
        lines.append("- " + ", ".join(skips))
    lines.append("")
    return lines


def _project_lines(entry: ProjectEntry) -> List[str]:
    lines = [
        "### %s" % escape(entry.label), "",
        "- Sessions: %d" % entry.sessions,
        "- Active time: %s" % humanize(entry.active_seconds),
        "- Turns: %d" % entry.turns,
        "- Tool calls: %d" % entry.tool_calls,
        "- Tokens: %s" % _tokens(entry.tokens),
    ]
    if entry.related_repos:
        lines.append("- Related repos: %s"
                     % ", ".join(escape(name) for name in entry.related_repos))
    lines.append("")
    return lines


def _projects_section(report: Report) -> List[str]:
    if not report.projects:
        return []
    lines = ["## Projects", ""]  # type: List[str]
    for entry in report.projects:
        lines.extend(_project_lines(entry))
    return lines


def _commit_bullet(commit: Commit, redact: bool) -> str:
    raw = redact_text(commit.subject) if redact else commit.subject
    subject = escape(raw)
    return "- %s (+%d/-%d, %d file%s)" % (
        subject, commit.insertions, commit.deletions, commit.files_changed,
        "" if commit.files_changed == 1 else "s")


def _repo_lines(entry: RepoEntry, redact: bool) -> List[str]:
    lines = ["### %s" % escape(entry.label), ""]  # type: List[str]
    lines.extend(_commit_bullet(commit, redact) for commit in entry.ai_commits)
    if entry.other_count:
        lines.append("- %d other commit%s (+%d/-%d)" % (
            entry.other_count, "" if entry.other_count == 1 else "s",
            entry.other_insertions, entry.other_deletions))
    lines.append("")
    return lines


def _repos_section(report: Report) -> List[str]:
    if not report.repos:
        return []
    lines = ["## Repos", ""]  # type: List[str]
    for entry in report.repos:
        lines.extend(_repo_lines(entry, report.redacted))
    return lines


def _footer(report: Report, now: datetime) -> List[str]:
    generated = now.strftime("%Y-%m-%d %H:%M UTC")
    badge = ("redaction: on" if report.redacted
            else "redaction: OFF -- raw paths and subjects below")
    lines = ["---", "Generated by agent-standup %s -- %s -- %s"
            % (__version__, generated, badge)]
    if report.git_disabled:
        lines.append("Warning: git axis disabled (%s)" % report.git_disabled_reason)
    for warning in report.warnings:
        lines.append("Warning: %s" % escape(warning))
    return lines


def render(report: Report, now: Optional[datetime] = None) -> str:
    """Render the full Markdown report as one string, ending with a newline."""
    lines = []  # type: List[str]
    lines.extend(_header(report))
    lines.extend(_projects_section(report))
    lines.extend(_repos_section(report))
    lines.extend(_footer(report, now or datetime.now(timezone.utc)))
    return "\n".join(lines) + "\n"
